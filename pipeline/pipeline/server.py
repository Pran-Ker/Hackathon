# --- Durable manifest ------------------------------------------------------
def _entry_for_dir(d: Path) -> dict | None:
    """Manifest entry for one generation dir, or None if it has no usable result.

    Prefers result.json (written by /imagine). Falls back to trace.json + known
    filenames so pre-existing timestamp-named runs survive a rebuild."""
    if not (d / "compiled" / "model.optimized.glb").is_file():
        return None

    result = d / "result.json"
    if result.is_file():
        r = json.loads(result.read_text())
        return {
            "id": d.name,
            "input": f"{d.name}/{r['input']}",
            "cutout": f"{d.name}/{r['cutout']}" if r.get("cutout") else None,
            "glb": f"{d.name}/{r['glb']}",
            "raw": f"{d.name}/{r['raw']}" if r.get("raw") else None,
            "native": f"{d.name}/compiled/Model.native.js"
            if (d / "compiled" / "Model.native.js").is_file()
            else None,
            "optSize": round(r["size_after"] / 1e6, 1) if r.get("size_after") else None,
            "rawSize": round(r["size_before"] / 1e6, 1) if r.get("size_before") else None,
        }

    # Legacy fallback: dir predates result.json.
    trace = d / "trace.json"
    t = json.loads(trace.read_text()) if trace.is_file() else {}
    if trace.is_file() and t.get("ok") is False:
        return None
    inp = next((p.name for p in sorted(d.glob("input.*"))), None)
    if not inp:
        return None
    cutout = next((p.name for p in sorted(d.glob("input_cutout.*"))), None)
    raw = "model.glb" if (d / "model.glb").is_file() else None
    return {
        "id": d.name,
        "input": f"{d.name}/{inp}",
        "cutout": f"{d.name}/{cutout}" if cutout else None,
        "glb": f"{d.name}/compiled/model.optimized.glb",
        "raw": f"{d.name}/{raw}" if raw else None,
        "native": f"{d.name}/compiled/Model.native.js"
        if (d / "compiled" / "Model.native.js").is_file()
        else None,
        "optSize": round(t["size_after"] / 1e6, 1) if t.get("size_after") else None,
        "rawSize": round(t["size_before"] / 1e6, 1) if t.get("size_before") else None,
    }


def _rebuild_manifest() -> list[dict]:
    """Scan outputs/imagine/ and rewrite manifest.json (newest first). This is
    what makes the studio sidebar durable across restarts. Written atomically so
    concurrent generations never observe a half-written manifest."""
    dirs = [d for d in IMAGINE_DIR.iterdir() if d.is_dir()]
    dirs.sort(key=lambda d: d.stat().st_mtime, reverse=True)
    entries = [e for d in dirs if (e := _entry_for_dir(d)) is not None]
    tmp = IMAGINE_DIR / "manifest.json.tmp"
    tmp.write_text(json.dumps(entries, indent=2))
    tmp.replace(IMAGINE_DIR / "manifest.json")
    return entries


# Serialize manifest rewrites so parallel /imagine calls don't clobber each other.
_manifest_lock = asyncio.Lock()


async def _refresh_manifest() -> None:
    async with _manifest_lock:
        await run_in_threadpool(_rebuild_manifest)


