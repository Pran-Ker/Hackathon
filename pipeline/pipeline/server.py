def _response(request: Request, work_dir: Path, result: dict, cached: bool, include_native: bool = True) -> dict:
    """Build the /imagine JSON response with request-host-derived URLs and
    ready-to-use Three.js code (standalone HTML always; native component when
    available and requested)."""
    glb_url = _files_url(request, work_dir / result["glb"])
    native_code = None
    if include_native and result.get("native"):
        try:
            native_code = (work_dir / result["native"]).read_text()
        except OSError:
            native_code = None
    return {
        "glb_url": glb_url,
        "component_url": _files_url(request, work_dir / result["component"]),
        "native_url": _files_url(request, work_dir / result["native"]) if result.get("native") else None,
        "name": result.get("name"),
        "tags": result.get("tags", []),
        "size_before": result.get("size_before"),
        "size_after": result.get("size_after"),
        "cached": cached,
        "threejs_html": _html_snippet(glb_url),
        "threejs_native": native_code,
    }


def _cached_result(work_dir: Path) -> dict | None:
    """Return a persisted result iff it is complete (result.json + the GLB it
    points at both exist). Partial/aborted runs return None so they re-run."""
    rj = work_dir / "result.json"
    if not rj.is_file():
        return None
    try:
        result = json.loads(rj.read_text())
    except (json.JSONDecodeError, OSError):
        return None
    if not (work_dir / result.get("glb", "")).is_file():
        return None
    return result


def _run_pipeline(work_dir: Path, src_path: Path) -> dict:
    """Blocking: isolate -> describe -> multiview -> image_to_3d -> compile.
    Writes trace.json and, on success, result.json (relative paths). Runs in a
    threadpool so the event loop stays responsive to health checks and cached
    hits while a long generation is in flight."""
    req_id = work_dir.name
    trace: dict = {"req_id": req_id, "input": src_path.name, "stages": {}}

    def _stage(name: str, fn):
        t0 = time.time()
        try:
            out = fn()
            trace["stages"][name] = {"ok": True, "seconds": round(time.time() - t0, 2)}
            return out
        except Exception:
            trace["stages"][name] = {"ok": False, "seconds": round(time.time() - t0, 2)}
            raise
        finally:
            print(f"[imagine {req_id}] {name}: {trace['stages'][name]}", flush=True)
            (work_dir / "trace.json").write_text(json.dumps(trace, indent=2))

    # Stage 1: background removal (also gives us a fal-hosted cutout URL).
    subject = _stage("isolate", lambda: isolate_subject(src_path, work_dir))

    # Optional semantic metadata (failsafe: returns None on any error).
    desc = _stage("describe", lambda: describe_subject(src_path))
    trace["name"] = desc["name"] if desc else None

    # Stage 1b (multiview): synthesize back/left/right views so Hunyuan
    # reconstructs a solid volume instead of a flat relief. Failsafe: an empty
    # result just falls back to single-view.
    views = _stage("multiview", lambda: generate_orbit_views(subject["cutout_url"]))
    trace["views"] = sorted(views.keys())

    # Stage 2: image -> 3D. Feed the hosted cutout URL to avoid a re-upload.
    raw_glb = _stage(
        "image_to_3d",
        lambda: image_to_3d(subject["cutout_url"], work_dir / "model.glb", extra_views=views),
    )

    # Stage 3: optimize + generate typed r3f component.
    compiled_dir = work_dir / "compiled"
    compiled = _stage("compile", lambda: compile_glb(raw_glb, compiled_dir))
    trace["size_before"] = compiled["size_before"]
    trace["size_after"] = compiled["size_after"]

    # Stage 4 (transpile): emit a native Three.js component from the RAW glb.
    # This is a bonus artifact — a failure must NOT fail the whole run.
    native_path = compiled_dir / "Model.native.js"
    native = None
    try:
        _stage(
            "transpile",
            lambda: transpile_glb_to_component(raw_glb, native_path, target_faces=40000),
        )
        if native_path.is_file():
            native = native_path.resolve().relative_to(work_dir).as_posix()
    except Exception:
        native = None

    trace["ok"] = True
    (work_dir / "trace.json").write_text(json.dumps(trace, indent=2))

    # result.json: relative paths + metadata. This is the durable record that
    # makes re-uploads idempotent and rebuilds the manifest after a restart.
    cutout = next((p.name for p in sorted(work_dir.glob("input_cutout.*"))), None)
    result = {
        "req_id": req_id,
        "input": src_path.name,
        "cutout": cutout,
        "raw": "model.glb",
        "glb": compiled["optimized_glb"].resolve().relative_to(work_dir).as_posix(),
        "component": compiled["component"].resolve().relative_to(work_dir).as_posix(),
        "native": native,
        "name": desc["name"] if desc else None,
        "tags": desc["tags"] if desc else [],
        "size_before": compiled["size_before"],
        "size_after": compiled["size_after"],
    }
    # Atomic write so a crash mid-write never leaves a half result.json that
    # would be read back as a (broken) cache hit.
    tmp = work_dir / "result.json.tmp"
    tmp.write_text(json.dumps(result, indent=2))
    tmp.replace(work_dir / "result.json")
    return result


# Per-content locks so two identical uploads racing in never run the pipeline
# twice — the second waits, then gets the first one's cached result.
_locks: dict[str, asyncio.Lock] = {}

IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".gif", ".tif", ".tiff"}


MAX_BATCH = 8


async def _imagine_one(request: Request, image: UploadFile, include_native: bool = True) -> tuple[int, dict]:
    """Run one image through the pipeline (content-addressed, idempotent). Returns
    (status_code, body). Safe to call concurrently for different images — the
    blocking pipeline runs in a threadpool and only *identical* images serialize
    on a shared per-content lock."""
    # Validate the upload is actually an image before spending any pipeline time.
    content_type = (image.content_type or "").lower()
    suffix = Path(image.filename or "upload.png").suffix.lower()
    if not (content_type.startswith("image/") or suffix in IMAGE_EXTS):
        return 400, {"error": "Upload must be an image (PNG, JPG, or WEBP)."}

    data = await image.read()
    if not data:
        return 400, {"error": "Uploaded image is empty."}

    # Content-addressed: same bytes -> same dir -> same result, forever.
    digest = hashlib.sha256(data).hexdigest()
    req_id = digest[:16]
    work_dir = IMAGINE_DIR / req_id

    # Fast path: already generated (survives restarts — no lock needed).
    cached = _cached_result(work_dir)
    if cached:
        print(f"[imagine {req_id}] cache hit (idempotent)", flush=True)
        return 200, _response(request, work_dir, cached, cached=True, include_native=include_native)

    lock = _locks.setdefault(digest, asyncio.Lock())
    async with lock:
        # Re-check: a racing identical request may have finished while we waited.
        cached = _cached_result(work_dir)
        if cached:
            return 200, _response(request, work_dir, cached, cached=True, include_native=include_native)

        work_dir.mkdir(parents=True, exist_ok=True)
        src_path = work_dir / f"input{suffix or '.png'}"
        src_path.write_bytes(data)

        try:
            result = await run_in_threadpool(_run_pipeline, work_dir, src_path)
        except Exception as exc:  # noqa: BLE001 - surface any pipeline failure as JSON
            import traceback

            traceback.print_exc()
            trace_path = work_dir / "trace.json"
            trace = json.loads(trace_path.read_text()) if trace_path.is_file() else {"req_id": req_id}
            trace["ok"] = False
            trace["error"] = str(exc)
            trace_path.write_text(json.dumps(trace, indent=2))
            return 500, {"error": f"3D generation failed: {exc}"}
        finally:
            _locks.pop(digest, None)

    await _refresh_manifest()  # keep the studio sidebar durable + current
    return 200, _response(request, work_dir, result, cached=False, include_native=include_native)


@app.post(
    "/imagine",
    response_model=ImagineResponse,
    tags=["generations"],
    summary="Photo → 3D model (single)",
    responses={
        400: {"model": ErrorResponse, "description": "Upload is not an image or is empty."},
        500: {"model": ErrorResponse, "description": "Pipeline failure (fal/compile error)."},
    },
)
async def imagine(
    request: Request,
    image: UploadFile = File(..., description="Photo of a single subject (PNG/JPG/WEBP)."),
    native: bool = Query(True, description="Include the self-contained native Three.js source in the response."),
):
    """Photo -> 3D: isolate subject, image_to_3d, compile to an optimized GLB
    + typed r3f component. Returns request-host-rooted URLs **and ready-to-use
    Three.js code** (`threejs_html`, `threejs_native`). Idempotent by image
    content, durable across restarts.

    First-time generation takes ~3-4 min; a repeat of the same image returns
    instantly with `cached: true`. To send several images at once, use
    `/imagine/batch`."""
    status, body = await _imagine_one(request, image, include_native=native)
    if status != 200:
        return _error(status, body["error"])
    return body


@app.post(
    "/imagine/batch",
    response_model=BatchResponse,
    tags=["generations"],
    summary="Photos → 3D models (parallel batch)",
    responses={400: {"model": ErrorResponse, "description": "No images, or too many (max 8)."}},
)
async def imagine_batch(
    request: Request,
    images: list[UploadFile] = File(..., description="2–8 photos in the 'images' field. Processed concurrently."),
    native: bool = Query(True, description="Include the self-contained native Three.js source per result."),
):
    """Send several images in one request; they run through the pipeline
    **concurrently** (wall-clock ≈ the slowest single image, not the sum). Each
    result is independent — one image failing does not fail the others.

    Every image is content-addressed, so duplicates (within the batch or from a
    previous call) return instantly as cache hits."""
    if not images:
        return _error(400, "Provide at least one image in the 'images' field.")
    if len(images) > MAX_BATCH:
        return _error(400, f"Too many images ({len(images)}); max {MAX_BATCH} per batch.")

    # Fan out: different images run in parallel, identical ones dedupe via lock.
    outcomes = await asyncio.gather(*[_imagine_one(request, im, include_native=native) for im in images])

    results = []
    for im, (status, body) in zip(images, outcomes):
        if status == 200:
            results.append({"filename": im.filename, "ok": True, "result": body})
        else:
            results.append({"filename": im.filename, "ok": False, "error": body.get("error")})
    return {"count": len(results), "results": results}


