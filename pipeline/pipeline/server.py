"""Local dev server: viewer-facing HTTP for the promptable-world pipeline.

Endpoints:
- GET  /api/health          liveness + LAN URL hints
- GET  /api/runs            durable manifest of every generation on disk
- POST /api/edit            OLD splat project: click-to-edit -> fal image (real)
- POST /imagine             Stage 5: photo -> isolated subject -> image_to_3d ->
                            optimized GLB + typed r3f component, served over HTTP.

Static files (the produced GLBs + components + studio.html) are mounted at
/files so the viewer can fetch them cross-origin.

## Sharing over Wi-Fi
Bind to every interface so phones/laptops on the same network can reach it:

    uv run uvicorn pipeline.server:app --host 0.0.0.0 --port 8000

Then open the studio at  http://<this-machine-LAN-IP>:8778/studio.html
The startup log prints the exact LAN URLs. Every produced URL is derived from
the request host (never hardcoded localhost), so a model generated by a remote
client loads on that remote client.

## Durable + idempotent
Each generation is keyed by the SHA-256 of the uploaded bytes and written to
outputs/imagine/<sha16>/. Re-uploading the same image (or a retry after a
dropped connection) returns the existing result instantly instead of re-running
the ~3-4 min pipeline. Results survive restarts: manifest.json is rebuilt from
disk on boot and after every generation.
"""

