"""Local dev server: viewer-facing HTTP for the promptable-world pipeline.

Endpoints:
- GET  /api/health          liveness + LAN URL hints
- GET  /api/runs            durable manifest of every generation on disk
- POST /api/edit            OLD splat project: click-to-edit -> fal image (real)
- POST /imagine             Stage 5: photo -> isolated subject -> image_to_3d ->
                            optimized GLB + typed r3f component, served over HTTP.

Static files (the produced GLBs + components + studio.html) are mounted at
/files so the viewer can fetch them cross-origin.

## Sharing over Wi-Fi
Bind to every interface so phones/laptops on the same network can reach it:

    uv run uvicorn pipeline.server:app --host 0.0.0.0 --port 8000

Then open the studio at  http://<this-machine-LAN-IP>:8778/studio.html
The startup log prints the exact LAN URLs. Every produced URL is derived from
the request host (never hardcoded localhost), so a model generated by a remote
client loads on that remote client.

## Durable + idempotent
Each generation is keyed by the SHA-256 of the uploaded bytes and written to
outputs/imagine/<sha16>/. Re-uploading the same image (or a retry after a
dropped connection) returns the existing result instantly instead of re-running
the ~3-4 min pipeline. Results survive restarts: manifest.json is rebuilt from
disk on boot and after every generation.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import socket
import time
from pathlib import Path

from fastapi import FastAPI, File, Request, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel
from starlette.concurrency import run_in_threadpool

from pipeline.compile_glb import compile_glb
from pipeline.generate import generate_edit_preview, image_to_3d
from pipeline.multiview import generate_orbit_views
from pipeline.subject import describe_subject, isolate_subject

# outputs/ lives at pipeline/outputs (one level above this package dir).
OUTPUTS_DIR = (Path(__file__).resolve().parent.parent / "outputs")
IMAGINE_DIR = OUTPUTS_DIR / "imagine"
IMAGINE_DIR.mkdir(parents=True, exist_ok=True)

app = FastAPI(title="promptable-world-pipeline")

app.add_middleware(
    CORSMiddleware,
    # Studio + vite dev origins vary (5173/5174, the static studio on 8778, and
    # any LAN IP a phone/laptop connects from). No credentials are used, so allow
    # any origin for dev simplicity.
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

# Serve everything under outputs/ at /files/... (CORSMiddleware wraps this too).
app.mount("/files", StaticFiles(directory=str(OUTPUTS_DIR)), name="files")


# --- URL helpers -----------------------------------------------------------
# URLs are built from the *incoming request* host, not a hardcoded localhost, so
# a client on another machine gets URLs that resolve back to this server.
def _files_url(request: Request, path: Path) -> str:
    """Absolute http URL for a file under OUTPUTS_DIR, rooted at the request host."""
    rel = Path(path).resolve().relative_to(OUTPUTS_DIR).as_posix()
    return f"{str(request.base_url).rstrip('/')}/files/{rel}"


def _lan_ip() -> str:
    """Best-effort primary LAN IP (no traffic is actually sent)."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


class Point(BaseModel):
    x: float
    y: float
    z: float


class EditRequest(BaseModel):
    point: Point
    prompt: str


class EditResponse(BaseModel):
    image_url: str
    note: str


# --- Durable manifest ------------------------------------------------------
def _entry_for_dir(d: Path) -> dict | None:
    """Manifest entry for one generation dir, or None if it has no usable result.

    Prefers result.json (written by /imagine). Falls back to trace.json + known
    filenames so pre-existing timestamp-named runs survive a rebuild."""
    if not (d / "compiled" / "model.optimized.glb").is_file():
        return None

    result = d / "result.json"
    if result.is_file():
        r = json.loads(result.read_text())
        return {
            "id": d.name,
            "input": f"{d.name}/{r['input']}",
            "cutout": f"{d.name}/{r['cutout']}" if r.get("cutout") else None,
            "glb": f"{d.name}/{r['glb']}",
            "raw": f"{d.name}/{r['raw']}" if r.get("raw") else None,
            "optSize": round(r["size_after"] / 1e6, 1) if r.get("size_after") else None,
            "rawSize": round(r["size_before"] / 1e6, 1) if r.get("size_before") else None,
        }

    # Legacy fallback: dir predates result.json.
    trace = d / "trace.json"
    t = json.loads(trace.read_text()) if trace.is_file() else {}
    if trace.is_file() and t.get("ok") is False:
        return None
    inp = next((p.name for p in sorted(d.glob("input.*"))), None)
    if not inp:
        return None
    cutout = next((p.name for p in sorted(d.glob("input_cutout.*"))), None)
    raw = "model.glb" if (d / "model.glb").is_file() else None
    return {
        "id": d.name,
        "input": f"{d.name}/{inp}",
        "cutout": f"{d.name}/{cutout}" if cutout else None,
        "glb": f"{d.name}/compiled/model.optimized.glb",
        "raw": f"{d.name}/{raw}" if raw else None,
        "optSize": round(t["size_after"] / 1e6, 1) if t.get("size_after") else None,
        "rawSize": round(t["size_before"] / 1e6, 1) if t.get("size_before") else None,
    }


def _rebuild_manifest() -> list[dict]:
    """Scan outputs/imagine/ and rewrite manifest.json (newest first). This is
    what makes the studio sidebar durable across restarts."""
    dirs = [d for d in IMAGINE_DIR.iterdir() if d.is_dir()]
    dirs.sort(key=lambda d: d.stat().st_mtime, reverse=True)
    entries = [e for d in dirs if (e := _entry_for_dir(d)) is not None]
    (IMAGINE_DIR / "manifest.json").write_text(json.dumps(entries, indent=2))
    return entries


@app.on_event("startup")
def _on_startup():
    entries = _rebuild_manifest()
    ip = _lan_ip()
    print(f"[server] {len(entries)} generation(s) on disk", flush=True)
    print(f"[server] studio (LAN):  http://{ip}:8778/studio.html", flush=True)
    print(f"[server] api    (LAN):  http://{ip}:8000/", flush=True)


@app.get("/api/health")
def health(request: Request):
    return {"ok": True, "lan_ip": _lan_ip(), "base_url": str(request.base_url)}


@app.get("/api/runs")
def runs():
    """Durable manifest of every generation currently on disk."""
    return _rebuild_manifest()


@app.post("/api/edit", response_model=EditResponse)
def edit(req: EditRequest):
    image_url = generate_edit_preview(req.prompt)
    return EditResponse(
        image_url=image_url,
        note="fal call is real; reconstruction/fusion into the 3D world is not implemented yet",
    )


def _error(status: int, message: str) -> JSONResponse:
    """JSON error response. CORSMiddleware wraps this so it stays cross-origin
    friendly (the viewer reads `error` off the body)."""
    return JSONResponse(status_code=status, content={"error": message})


def _response(request: Request, work_dir: Path, result: dict, cached: bool) -> dict:
    """Build the /imagine JSON response with request-host-derived URLs."""
    return {
        "glb_url": _files_url(request, work_dir / result["glb"]),
        "component_url": _files_url(request, work_dir / result["component"]),
        "name": result.get("name"),
        "tags": result.get("tags", []),
        "size_before": result.get("size_before"),
        "size_after": result.get("size_after"),
        "cached": cached,
    }


def _cached_result(work_dir: Path) -> dict | None:
    """Return a persisted result iff it is complete (result.json + the GLB it
    points at both exist). Partial/aborted runs return None so they re-run."""
    rj = work_dir / "result.json"
    if not rj.is_file():
        return None
    try:
        result = json.loads(rj.read_text())
    except (json.JSONDecodeError, OSError):
        return None
    if not (work_dir / result.get("glb", "")).is_file():
        return None
    return result


def _run_pipeline(work_dir: Path, src_path: Path) -> dict:
    """Blocking: isolate -> describe -> multiview -> image_to_3d -> compile.
    Writes trace.json and, on success, result.json (relative paths). Runs in a
    threadpool so the event loop stays responsive to health checks and cached
    hits while a long generation is in flight."""
    req_id = work_dir.name
    trace: dict = {"req_id": req_id, "input": src_path.name, "stages": {}}

    def _stage(name: str, fn):
        t0 = time.time()
        try:
            out = fn()
            trace["stages"][name] = {"ok": True, "seconds": round(time.time() - t0, 2)}
            return out
        except Exception:
            trace["stages"][name] = {"ok": False, "seconds": round(time.time() - t0, 2)}
            raise
        finally:
            print(f"[imagine {req_id}] {name}: {trace['stages'][name]}", flush=True)
            (work_dir / "trace.json").write_text(json.dumps(trace, indent=2))

    # Stage 1: background removal (also gives us a fal-hosted cutout URL).
    subject = _stage("isolate", lambda: isolate_subject(src_path, work_dir))

    # Optional semantic metadata (failsafe: returns None on any error).
    desc = _stage("describe", lambda: describe_subject(src_path))
    trace["name"] = desc["name"] if desc else None

    # Stage 1b (multiview): synthesize back/left/right views so Hunyuan
    # reconstructs a solid volume instead of a flat relief. Failsafe: an empty
    # result just falls back to single-view.
    views = _stage("multiview", lambda: generate_orbit_views(subject["cutout_url"]))
    trace["views"] = sorted(views.keys())

    # Stage 2: image -> 3D. Feed the hosted cutout URL to avoid a re-upload.
    raw_glb = _stage(
        "image_to_3d",
        lambda: image_to_3d(subject["cutout_url"], work_dir / "model.glb", extra_views=views),
    )

    # Stage 3: optimize + generate typed r3f component.
    compiled_dir = work_dir / "compiled"
    compiled = _stage("compile", lambda: compile_glb(raw_glb, compiled_dir))
    trace["size_before"] = compiled["size_before"]
    trace["size_after"] = compiled["size_after"]
    trace["ok"] = True
    (work_dir / "trace.json").write_text(json.dumps(trace, indent=2))

    # result.json: relative paths + metadata. This is the durable record that
    # makes re-uploads idempotent and rebuilds the manifest after a restart.
    cutout = next((p.name for p in sorted(work_dir.glob("input_cutout.*"))), None)
    result = {
        "req_id": req_id,
        "input": src_path.name,
        "cutout": cutout,
        "raw": "model.glb",
        "glb": compiled["optimized_glb"].resolve().relative_to(work_dir).as_posix(),
        "component": compiled["component"].resolve().relative_to(work_dir).as_posix(),
        "name": desc["name"] if desc else None,
        "tags": desc["tags"] if desc else [],
        "size_before": compiled["size_before"],
        "size_after": compiled["size_after"],
    }
    # Atomic write so a crash mid-write never leaves a half result.json that
    # would be read back as a (broken) cache hit.
    tmp = work_dir / "result.json.tmp"
    tmp.write_text(json.dumps(result, indent=2))
    tmp.replace(work_dir / "result.json")
    return result


# Per-content locks so two identical uploads racing in never run the pipeline
# twice — the second waits, then gets the first one's cached result.
_locks: dict[str, asyncio.Lock] = {}

IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".gif", ".tif", ".tiff"}


@app.post("/imagine")
async def imagine(request: Request, image: UploadFile = File(...)):
    """Photo -> 3D: isolate subject, image_to_3d, compile to an optimized GLB
    + typed r3f component. Idempotent by image content, durable across restarts,
    and returns URLs rooted at the request host so remote clients work."""
    # Validate the upload is actually an image before spending any pipeline time.
    content_type = (image.content_type or "").lower()
    suffix = Path(image.filename or "upload.png").suffix.lower()
    if not (content_type.startswith("image/") or suffix in IMAGE_EXTS):
        return _error(400, "Upload must be an image (PNG, JPG, or WEBP).")

    data = await image.read()
    if not data:
        return _error(400, "Uploaded image is empty.")

    # Content-addressed: same bytes -> same dir -> same result, forever.
    digest = hashlib.sha256(data).hexdigest()
    req_id = digest[:16]
    work_dir = IMAGINE_DIR / req_id

    # Fast path: already generated (survives restarts — no lock needed).
    cached = _cached_result(work_dir)
    if cached:
        print(f"[imagine {req_id}] cache hit (idempotent)", flush=True)
        return _response(request, work_dir, cached, cached=True)

    lock = _locks.setdefault(digest, asyncio.Lock())
    async with lock:
        # Re-check: a racing identical request may have finished while we waited.
        cached = _cached_result(work_dir)
        if cached:
            return _response(request, work_dir, cached, cached=True)

        work_dir.mkdir(parents=True, exist_ok=True)
        src_path = work_dir / f"input{suffix or '.png'}"
        src_path.write_bytes(data)

        try:
            result = await run_in_threadpool(_run_pipeline, work_dir, src_path)
        except Exception as exc:  # noqa: BLE001 - surface any pipeline failure as JSON
            import traceback

            traceback.print_exc()
            trace_path = work_dir / "trace.json"
            trace = json.loads(trace_path.read_text()) if trace_path.is_file() else {"req_id": req_id}
            trace["ok"] = False
            trace["error"] = str(exc)
            trace_path.write_text(json.dumps(trace, indent=2))
            return _error(500, f"3D generation failed: {exc}")
        finally:
            _locks.pop(digest, None)

    _rebuild_manifest()  # keep the studio sidebar durable + current
    return _response(request, work_dir, result, cached=False)
