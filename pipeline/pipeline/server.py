# --- URL helpers -----------------------------------------------------------
# URLs are built from the *incoming request* host, not a hardcoded localhost, so
# a client on another machine gets URLs that resolve back to this server.
def _files_url(request: Request, path: Path) -> str:
    """Absolute http URL for a file under OUTPUTS_DIR, rooted at the request host."""
    rel = Path(path).resolve().relative_to(OUTPUTS_DIR).as_posix()
    return f"{str(request.base_url).rstrip('/')}/files/{rel}"


def _lan_ip() -> str:
    """Best-effort primary LAN IP (no traffic is actually sent)."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


